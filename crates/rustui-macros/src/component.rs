use proc_macro::TokenStream;
use quote::{format_ident, quote};
use std::collections::HashMap;
use syn::punctuated::Punctuated;
use syn::{Attribute, Expr, Fields, Ident, ItemStruct, Type, parse_quote};

fn collect_cfg_requirements(
    meta: &syn::Meta,
    parent_condition: Option<proc_macro2::TokenStream>,
    requirements: &mut Vec<proc_macro2::TokenStream>,
) -> syn::Result<()> {
    match meta {
        syn::Meta::List(list) if list.path.is_ident("cfg") => {
            let predicate = &list.tokens;
            requirements.push(match parent_condition {
                Some(parent) => quote!(any(not(#parent), #predicate)),
                None => quote!(#predicate),
            });
        }
        syn::Meta::List(list) if list.path.is_ident("cfg_attr") => {
            let arguments =
                list.parse_args_with(Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated)?;
            let mut arguments = arguments.into_iter();
            let condition = arguments
                .next()
                .ok_or_else(|| syn::Error::new_spanned(list, "`cfg_attr` requires a condition"))?;
            let condition = match parent_condition {
                Some(parent) => quote!(all(#parent, #condition)),
                None => quote!(#condition),
            };
            for attribute in arguments {
                collect_cfg_requirements(&attribute, Some(condition.clone()), requirements)?;
            }
        }
        _ => {}
    }

    Ok(())
}

fn cfg_presence(attributes: &[Attribute]) -> syn::Result<Option<proc_macro2::TokenStream>> {
    let mut requirements = Vec::new();
    for attribute in attributes.iter().filter(|attribute| {
        attribute.path().is_ident("cfg") || attribute.path().is_ident("cfg_attr")
    }) {
        collect_cfg_requirements(&attribute.meta, None, &mut requirements)?;
    }

    Ok((!requirements.is_empty()).then(|| quote!(all(#(#requirements),*))))
}

fn state_attribute_index(attributes: &[Attribute]) -> syn::Result<Option<usize>> {
    fn has_nested_state_attribute(meta: &syn::Meta) -> syn::Result<bool> {
        let syn::Meta::List(list) = meta else {
            return Ok(false);
        };
        if !list.path.is_ident("cfg_attr") {
            return Ok(false);
        }

        let arguments =
            list.parse_args_with(Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated)?;
        for nested in arguments.into_iter().skip(1) {
            if nested.path().is_ident("state") || has_nested_state_attribute(&nested)? {
                return Ok(true);
            }
        }
        Ok(false)
    }

    for attribute in attributes
        .iter()
        .filter(|attribute| attribute.path().is_ident("cfg_attr"))
    {
        if has_nested_state_attribute(&attribute.meta)? {
            return Err(syn::Error::new_spanned(
                attribute,
                "a component field's `#[state(...)]` attribute must not be nested inside `#[cfg_attr(...)]`",
            ));
        }
    }

    let mut state_attributes = attributes
        .iter()
        .enumerate()
        .filter(|(_, attribute)| attribute.path().is_ident("state"));
    let Some((index, _)) = state_attributes.next() else {
        return Ok(None);
    };
    if let Some((_, duplicate)) = state_attributes.next() {
        return Err(syn::Error::new_spanned(
            duplicate,
            "a component field may only have one `#[state(...)]` attribute",
        ));
    }
    Ok(Some(index))
}

fn state_accessor_names(field: &Ident) -> [Ident; 5] {
    let field_name = field.to_string();
    let field_name = field_name.strip_prefix("r#").unwrap_or(&field_name);
    [
        field.clone(),
        format_ident!("set_{field_name}"),
        format_ident!("update_{field_name}"),
        format_ident!("{field_name}_binding"),
        format_ident!("{field_name}_state"),
    ]
}

fn validate_state_accessor_names(state_fields: &[(Ident, Type, Expr)]) -> syn::Result<()> {
    let mut generated_methods = HashMap::<String, Ident>::new();

    for (field, _, _) in state_fields {
        for method in state_accessor_names(field) {
            let method_name = method.to_string();
            let method_name = method_name.strip_prefix("r#").unwrap_or(&method_name);
            if matches!(method_name, "action" | "action_if_changed") {
                return Err(syn::Error::new_spanned(
                    field,
                    format!(
                        "state field `{field}` generates accessor `{method}`, which conflicts with a helper method generated by `#[component]`"
                    ),
                ));
            }
            if let Some(previous_field) =
                generated_methods.insert(method_name.to_owned(), field.clone())
            {
                return Err(syn::Error::new_spanned(
                    field,
                    format!(
                        "state field `{field}` generates accessor `{method}`, which conflicts with the accessor generated for state field `{previous_field}`"
                    ),
                ));
            }
        }
    }

    Ok(())
}

pub fn expand(item: TokenStream) -> syn::Result<TokenStream> {
    expand_tokens(item.into()).map(Into::into)
}

fn expand_tokens(item: proc_macro2::TokenStream) -> syn::Result<proc_macro2::TokenStream> {
    let mut structure = syn::parse2::<ItemStruct>(item)?;
    let component_attributes: Vec<Attribute> = cfg_presence(&structure.attrs)?
        .map(|presence| vec![parse_quote!(#[cfg(#presence)])])
        .unwrap_or_default();
    let Fields::Named(fields) = &mut structure.fields else {
        return Err(syn::Error::new_spanned(
            &structure,
            "`#[component]` currently requires a struct with named fields",
        ));
    };

    let mut state_fields = Vec::<(Ident, Type, Expr, Vec<Attribute>)>::new();
    let mut default_fields = Vec::<(Ident, Type, Vec<Attribute>)>::new();

    for field in &mut fields.named {
        let conditional_attributes = cfg_presence(&field.attrs)?
            .map(|presence| vec![parse_quote!(#[cfg(#presence)])])
            .unwrap_or_default();
        let Some(index) = state_attribute_index(&field.attrs)? else {
            let name = field.ident.clone().expect("named fields have identifiers");
            default_fields.push((name, field.ty.clone(), conditional_attributes));
            continue;
        };

        let attribute = field.attrs.remove(index);
        let initial_value = attribute.parse_args::<Expr>()?;
        let name = field.ident.clone().expect("named fields have identifiers");
        state_fields.push((
            name,
            field.ty.clone(),
            initial_value,
            conditional_attributes,
        ));
    }

    validate_state_accessor_names(
        &state_fields
            .iter()
            // Conditional fields may not exist in the active build. Leave
            // those collisions to Rust's cfg expansion and duplicate-item
            // checks instead of rejecting valid configurations here.
            .filter(|(_, _, _, attributes)| attributes.is_empty())
            .map(|(field, ty, initial, _)| (field.clone(), ty.clone(), initial.clone()))
            .collect::<Vec<_>>(),
    )?;

    let name = &structure.ident;
    let generics = &structure.generics;
    let state_initializers = state_fields
        .iter()
        .map(|(field, _, initial, attributes)| quote!(#(#attributes)* #field: #initial));
    let default_initializers = default_fields
        .iter()
        .map(|(field, _, attributes)| {
            quote!(#(#attributes)* #field: ::core::default::Default::default())
        });
    let accessors = state_fields.iter().map(|(field, ty, _, attributes)| {
        let [_, setter, updater, binding, state] = state_accessor_names(field);
        quote! {
            #(#attributes)*
            pub fn #field(&self) -> #ty
            where
                #ty: ::core::clone::Clone,
            {
                self.#field.clone()
            }

            #(#attributes)*
            pub fn #setter(&mut self, value: #ty) -> bool
            where
                #ty: ::core::cmp::PartialEq,
            {
                if self.#field == value {
                    return false;
                }
                self.#field = value;
                true
            }

            #(#attributes)*
            pub fn #updater<Output>(
                &mut self,
                update: impl ::core::ops::FnOnce(&mut #ty) -> Output,
            ) -> Output {
                update(&mut self.#field)
            }

            #(#attributes)*
            pub fn #binding(&self) -> ::rustui::runtime::Binding<#ty>
            where
                Self: 'static,
                #ty: ::core::clone::Clone + 'static,
            {
                ::rustui::runtime::Binding::new(
                    self.#field.clone(),
                    |component: &Self| component.#field.clone(),
                    |component: &mut Self, value| component.#field = value,
                )
            }

            #(#attributes)*
            pub fn #state(&self) -> ::rustui::runtime::State<'_, #ty>
            where
                Self: 'static,
                #ty: ::core::clone::Clone + 'static,
            {
                ::rustui::runtime::State::new(&self.#field, self.#binding())
            }
        }
    });

    let mut default_generics = generics.clone();
    let (impl_generics, type_generics, where_clause) = generics.split_for_impl();
    let mut conditional_default_requirements = Vec::new();
    for (index, (_, ty, attributes)) in default_fields.iter().enumerate() {
        if let Some(presence) = cfg_presence(attributes)? {
            let requirement = format_ident!("__RustUIDefaultRequirement{index}");
            default_generics
                .make_where_clause()
                .predicates
                .push(parse_quote!(<Self as #requirement>::Field: ::core::default::Default));
            conditional_default_requirements.push(quote! {
                trait #requirement { type Field; }
                impl #impl_generics #requirement for #name #type_generics #where_clause {
                    #[cfg(#presence)]
                    type Field = #ty;
                    #[cfg(not(#presence))]
                    type Field = ();
                }
            });
        } else {
            default_generics
                .make_where_clause()
                .predicates
                .push(parse_quote!(#ty: ::core::default::Default));
        }
    }
    let (default_impl_generics, default_type_generics, default_where_clause) =
        default_generics.split_for_impl();

    let default_impl = quote! {
        impl #default_impl_generics ::core::default::Default for #name #default_type_generics
            #default_where_clause
        {
            fn default() -> Self {
                Self {
                    #(#state_initializers,)*
                    #(#default_initializers,)*
                }
            }
        }
    };
    let default_impl = if conditional_default_requirements.is_empty() {
        default_impl
    } else {
        quote! {
            const _: () = {
                #(#conditional_default_requirements)*
                #default_impl
            };
        }
    };

    Ok(quote! {
        #structure
        #(#component_attributes)*
        #default_impl

        #(#component_attributes)*
        impl #impl_generics #name #type_generics #where_clause {
            #(#accessors)*

            pub fn action(
                &self,
                handler: fn(&mut Self),
            ) -> ::rustui::runtime::Action {
                ::rustui::runtime::Action::new(handler)
            }

            pub fn action_if_changed(
                &self,
                handler: fn(&mut Self) -> bool,
            ) -> ::rustui::runtime::Action {
                ::rustui::runtime::Action::new_if_changed(handler)
            }
        }
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn duplicate_state_attributes_are_rejected_at_the_macro_boundary() {
        let field: syn::Field = syn::parse_quote! {
            #[state(0)]
            #[state(1)]
            count: usize
        };

        let error = state_attribute_index(&field.attrs).unwrap_err();

        assert_eq!(
            error.to_string(),
            "a component field may only have one `#[state(...)]` attribute"
        );
    }

    #[test]
    fn conditionally_nested_state_attributes_are_rejected_at_the_macro_boundary() {
        let error = expand_tokens(quote! {
            struct Conditional {
                #[cfg_attr(feature = "conditional", state(0))]
                count: usize,
            }
        })
        .unwrap_err();

        assert_eq!(
            error.to_string(),
            "a component field's `#[state(...)]` attribute must not be nested inside `#[cfg_attr(...)]`"
        );

        let recursively_nested_error = expand_tokens(quote! {
            struct Conditional {
                #[cfg_attr(feature = "outer", cfg_attr(feature = "inner", state(0)))]
                count: usize,
            }
        })
        .unwrap_err();

        assert_eq!(
            recursively_nested_error.to_string(),
            "a component field's `#[state(...)]` attribute must not be nested inside `#[cfg_attr(...)]`"
        );
    }

    #[test]
    fn generated_state_accessors_reject_cross_field_name_collisions() {
        let state_fields = vec![
            (format_ident!("count"), parse_quote!(usize), parse_quote!(0)),
            (
                format_ident!("set_count"),
                parse_quote!(bool),
                parse_quote!(false),
            ),
        ];

        let error = validate_state_accessor_names(&state_fields).unwrap_err();

        assert_eq!(
            error.to_string(),
            "state field `set_count` generates accessor `set_count`, which conflicts with the accessor generated for state field `count`"
        );
    }

    #[test]
    fn cfg_disabled_field_does_not_trigger_an_accessor_collision() {
        expand_tokens(quote! {
            struct Conditional {
                #[cfg(any())]
                #[state(0)]
                count: usize,
                #[state(false)]
                set_count: bool,
            }
        })
        .expect("the disabled field cannot collide with `set_count`");
    }

    #[test]
    fn generated_state_accessors_reject_component_helper_name_collisions() {
        for name in ["action", "action_if_changed"] {
            let field = syn::parse_str::<Ident>(name).unwrap();
            let error =
                validate_state_accessor_names(&[(field, parse_quote!(usize), parse_quote!(0))])
                    .unwrap_err();

            assert_eq!(
                error.to_string(),
                format!(
                    "state field `{name}` generates accessor `{name}`, which conflicts with a helper method generated by `#[component]`"
                )
            );
        }
    }

    #[test]
    fn generated_state_accessors_reject_raw_identifier_name_collisions() {
        let raw_helper = syn::parse_str::<Ident>("r#action").unwrap();
        let error =
            validate_state_accessor_names(&[(raw_helper, parse_quote!(usize), parse_quote!(0))])
                .unwrap_err();
        assert!(error.to_string().contains("conflicts with a helper method"));

        let first = syn::parse_str::<Ident>("value").unwrap();
        let second = syn::parse_str::<Ident>("r#value_binding").unwrap();
        let error = validate_state_accessor_names(&[
            (first, parse_quote!(usize), parse_quote!(0)),
            (second, parse_quote!(usize), parse_quote!(0)),
        ])
        .unwrap_err();
        assert!(
            error
                .to_string()
                .contains("conflicts with the accessor generated")
        );
    }

    #[test]
    fn generated_state_accessors_normalize_raw_keyword_field_names() {
        let field = syn::parse_str::<Ident>("r#type").unwrap();
        let names = state_accessor_names(&field);

        assert_eq!(
            names.iter().map(ToString::to_string).collect::<Vec<_>>(),
            [
                "r#type",
                "set_type",
                "update_type",
                "type_binding",
                "type_state"
            ]
        );
        validate_state_accessor_names(&[(field, parse_quote!(usize), parse_quote!(0))]).unwrap();
    }

    #[test]
    fn generated_component_items_preserve_conditional_field_attributes() {
        let expanded = expand_tokens(quote! {
            struct Conditional<T> {
                #[cfg_attr(any(), cfg(any()))]
                #[cfg(any())]
                #[state(T::default())]
                conditional_state: T,
                #[cfg_attr(any(), cfg(any()))]
                #[cfg(any())]
                conditional_default: T,
                visible: usize,
            }
        })
        .unwrap();
        let syntax = syn::parse2::<syn::File>(expanded.clone()).unwrap();
        let component_impl = syntax
            .items
            .iter()
            .find_map(|item| match item {
                syn::Item::Impl(item)
                    if item.items.iter().any(|member| {
                        matches!(
                            member,
                            syn::ImplItem::Fn(method)
                                if method.sig.ident == "conditional_state"
                        )
                    }) =>
                {
                    Some(item)
                }
                _ => None,
            })
            .expect("generated component impl");
        for name in [
            "conditional_state",
            "set_conditional_state",
            "update_conditional_state",
            "conditional_state_binding",
            "conditional_state_state",
        ] {
            let method = component_impl
                .items
                .iter()
                .find_map(|member| match member {
                    syn::ImplItem::Fn(method) if method.sig.ident == name => Some(method),
                    _ => None,
                })
                .unwrap_or_else(|| panic!("generated accessor `{name}`"));
            assert!(
                method
                    .attrs
                    .iter()
                    .any(|attribute| attribute.path().is_ident("cfg")),
                "generated accessor `{name}` is missing cfg"
            );
            assert!(
                method
                    .attrs
                    .iter()
                    .all(|attribute| !attribute.path().is_ident("cfg_attr")),
                "generated accessor `{name}` must not inherit field-only cfg_attr attributes"
            );
        }

        let expanded = expanded.to_string();

        assert_eq!(expanded.matches("cfg_attr").count(), 2);
        assert!(expanded.contains("conditional_state"));
        assert!(expanded.contains("conditional_default"));
    }

    #[test]
    fn generated_impls_preserve_component_cfg() {
        let expanded = expand_tokens(quote! {
            #[cfg(any())]
            struct Disabled {
                value: usize,
            }
        })
        .unwrap();
        let syntax = syn::parse2::<syn::File>(expanded).unwrap();
        let generated_impls = syntax
            .items
            .iter()
            .filter_map(|item| match item {
                syn::Item::Impl(item) => Some(item),
                _ => None,
            })
            .collect::<Vec<_>>();

        assert_eq!(generated_impls.len(), 2);
        assert!(generated_impls.iter().all(|item| {
            item.attrs
                .iter()
                .any(|attribute| attribute.path().is_ident("cfg"))
        }));
    }
}
