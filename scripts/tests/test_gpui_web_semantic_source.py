#!/usr/bin/env python3
"""Source wiring regressions; actual Rust/browser validation remains separate."""
from pathlib import Path
import unittest
ROOT = Path(__file__).resolve().parents[2]
def source(path): return (ROOT / path).read_text()
def body(text, marker):
 start=text.index(marker); start=text.index('{', start); depth=1; end=start+1
 while depth:
  depth += (text[end]=='{')-(text[end]=='}'); end+=1
 return text[start+1:end-1]
class SemanticSource(unittest.TestCase):
 def test_core_frame_order(self):
  s=source('vendor/gpui-pre-0.3.9/src/window.rs')
  draw=body(s,'pub fn draw(')
  self.assertLess(draw.index('self.draw_roots(cx)'),draw.index('self.install_platform_input_handler('))
  roots=body(s,'fn draw_roots(')
  self.assertIn('self.platform_window.a11y_tree_update(tree_update)',roots)
  install=body(s,'fn install_platform_input_handler(')
  self.assertEqual(install.split()[-2:], ['self.platform_window.text_input_owner_ready();', 'accepts'][-3:])
 def test_rust_queue_projects_current_owner_then_commits(self):
  s=source('vendor/gpui-pre-web-0.3.9/src/a11y.rs')
  update=body(s,'pub(crate) fn update(')
  self.assertIn('self.pending.push(update)',update); self.assertNotIn('project(',update)
  ready=body(s,'pub(crate) fn frame_ready(')
  self.assertLess(ready.index('project(&mut state, update, self.ime.is_secure())'),ready.index('self.dom.update('))
  self.assertLess(ready.index('self.dom.update('),ready.index('self.dom.frame_ready()'))
  for method in ('composition_started','owner_changed'): self.assertIn('pub(crate) fn '+method+'(',s)
 def test_web_ready_and_bindings(self):
  s=source('vendor/gpui-pre-web-0.3.9/src/window.rs')
  ready=body(s,'fn text_input_owner_ready(')
  self.assertIn('frame_ready(',ready)
  bindings=source('vendor/gpui-pre-web-0.3.9/src/a11y_dom.rs')
  for name in ('frameReady','compositionStarted','ownerChanged'): self.assertIn(name,bindings)
  events=source('vendor/gpui-pre-web-0.3.9/src/events.rs')
  self.assertIn('pub(crate) fn schedule_ime_mirror_sync(',events)
