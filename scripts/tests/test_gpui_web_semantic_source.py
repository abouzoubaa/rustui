 def test_canonical_dom_edit_import_and_reconciliation(self):
  events=source('vendor/gpui-pre-web-0.3.9/src/events.rs')
  imported=body(events,'fn register_input(')
  self.assertIn('crate::ime_edit::plan_ime_edit(',imported)
  self.assertIn('this.ime_mirror.window_start()',imported)
  self.assertLess(imported.index('text_window_matches('),imported.index('handler.replace_text_in_range('))
  self.assertIn('Some(edit.range), &edit.text',imported)
  self.assertNotIn('selection.range.end + removed_after_selection',imported)
  self.assertTrue(imported.count('schedule_ime_mirror_sync()')>=2)
  keydown=body(events,'fn register_key_down(')
  self.assertIn('!result.propagate || result.default_prevented',keydown)
  mirror=source('vendor/gpui-pre-web-0.3.9/src/ime_mirror.rs')
  self.assertIn('pub(crate) fn text_window_matches(',mirror)
  self.assertIn('text_window_matches(handler,mirror.window_hint.get()', ''.join(mirror.split()))
  planner=source('vendor/gpui-pre-web-0.3.9/src/ime_edit.rs')
  for case in ('full_selection_deletion_ignores_new_application_caret','empty_replacement_deletes_entire_window','supplementary_scalar_replacement_does_not_split_shared_surrogates'):
   self.assertIn(case,planner)
 def test_shared_absolute_selection_import_precedes_edit_consumers(self):
  events=source('vendor/gpui-pre-web-0.3.9/src/events.rs')
  keydown=body(events,'fn register_key_down(')
  self.assertLess(keydown.index('import_current_selection(&this)'),keydown.index('this.dispatch_input(PlatformInput::KeyDown'))
  self.assertIn('SelectionImport::Rejected',keydown)
  before=body(events,'fn register_before_input(')
  self.assertLess(before.index('import_current_selection(&this)'),before.index('match event.input_type()'))
  self.assertIn('SelectionImport::Current',before)
  selection=body(events,'fn register_selection_change(')
  self.assertIn('import_current_selection(&this)',selection)
  self.assertNotIn('handler.set_selected_text_range(',selection)
  mirror=source('vendor/gpui-pre-web-0.3.9/src/ime_mirror.rs')
  imported=body(mirror,'pub(crate) fn import_current_selection(')
  self.assertLess(imported.index('text_window_matches('),imported.index('plan_ime_selection('))
  self.assertIn('SelectionPlan::KeepApplication=>{SelectionImport::ApplicationNewer}', ''.join(imported.split()))
  planner=source('vendor/gpui-pre-web-0.3.9/src/ime_edit.rs')
  for case in ('native_select_all_before_next_key_imports_full_absolute_range','gpui_select_all_before_mirror_sync_is_preserved','conflicting_model_and_native_selection_is_rejected'):
   self.assertIn(case,planner)
